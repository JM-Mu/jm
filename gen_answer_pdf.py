a('④工具坐标系：将工具中心点（TCP）设为零位，定义工具的位置和方向，常缩写为TCPF，其中心点缩写为TCP。执行程序时机器人将TCP移至编程位置；所有机器人在手腕处都有预定义工具坐标系tool0，新工具坐标系可定义为tool0的偏移值。')

